#!/usr/bin/env python3
"""Generate contract models from schemas/ (JSON Schema 2020-12) and namespace.json.

  python tools/codegen/generate.py --lang python  --out <dir> [--package hub_contracts]
  python tools/codegen/generate.py --lang ts      --out <dir>
  python tools/codegen/generate.py --lang swift   --out <dir>
  python tools/codegen/generate.py --lang kotlin  --out <dir> [--package hubcontracts]
  ... --check   compare with the files in <dir> instead of writing; exit 1 on any difference

Stdlib only, deterministic (no timestamps, sorted output). The output directory is owned by the
generator: files carrying the generated-file marker that are no longer produced are deleted
(write mode) or reported (check mode); other files are left alone.
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from hubgen.ir import SchemaError, build_ir  # noqa: E402

REPO = HERE.parent.parent
MARKER = "Generated by contracts/tools/codegen/generate.py - DO NOT EDIT."
LANGS = ("python", "ts", "swift", "kotlin")


def generate(lang: str, package: str | None, repo: Path = REPO) -> dict[str, str]:
    from hubgen import emit_kotlin, emit_python, emit_swift, emit_typescript  # noqa: PLC0415

    ir = build_ir(repo)
    if lang == "python":
        return emit_python.emit(ir, package or "hub_contracts")
    if lang == "ts":
        return emit_typescript.emit(ir)
    if lang == "swift":
        return emit_swift.emit(ir)
    if lang == "kotlin":
        return emit_kotlin.emit(ir, package or "hubcontracts")
    raise ValueError(lang)


def owned_files(out: Path) -> set[str]:
    found = set()
    if not out.exists():
        return found
    for p in out.rglob("*"):
        if not p.is_file() or "__pycache__" in p.parts:
            continue
        try:
            head = p.read_text(encoding="utf-8", errors="ignore")[:400]
        except OSError:
            continue
        if MARKER in head:
            found.add(p.relative_to(out).as_posix())
    return found


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lang", required=True, choices=LANGS)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--package", help="python package name (hub_contracts) or kotlin package (hubcontracts)")
    ap.add_argument("--check", action="store_true", help="verify instead of writing; exit 1 when stale")
    ap.add_argument("--contracts", type=Path, default=REPO, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)

    try:
        files = generate(args.lang, args.package, args.contracts)
    except SchemaError as exc:
        print(f"codegen: unsupported schema construct: {exc}", file=sys.stderr)
        return 2

    out: Path = args.out
    stale = sorted(owned_files(out) - set(files))
    if args.check:
        problems = 0
        for rel, content in sorted(files.items()):
            target = out / rel
            current = target.read_text(encoding="utf-8") if target.exists() else None
            if current != content:
                problems += 1
                print(f"stale: {target}")
                diff = difflib.unified_diff(
                    (current or "").splitlines(), content.splitlines(), f"{rel} (checked in)", f"{rel} (generated)", lineterm="", n=1
                )
                for i, line in enumerate(diff):
                    if i >= 40:
                        print("  ...")
                        break
                    print("  " + line)
        for rel in stale:
            problems += 1
            print(f"obsolete generated file: {out / rel}")
        if problems:
            print(f"\n{problems} file(s) out of date. Regenerate: python tools/codegen/generate.py --lang {args.lang} --out {out}"
                  + (f" --package {args.package}" if args.package else ""))
            return 1
        print(f"codegen {args.lang}: {len(files)} files up to date in {out}")
        return 0

    for rel, content in sorted(files.items()):
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")
    for rel in stale:
        (out / rel).unlink()
    print(f"codegen {args.lang}: wrote {len(files)} files to {out}" + (f", removed {len(stale)} obsolete" if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
