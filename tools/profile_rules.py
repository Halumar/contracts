#!/usr/bin/env python3
"""Profile rule catalog: derived schema and consistency checks.

  python tools/profile_rules.py           write schemas/common/resolved-rules.json
  python tools/profile_rules.py --check   exit 1 when it is stale or the catalog is inconsistent

schemas/common/resolved-rules.json is generated from schemas/common/profile-rule-values.json (one
typed entry per rule for client_config.rules). tools/validate.py calls check() as well, so the catalog
(data/profile-rules.json), the suggestions (data/profile-suggestions.json), the value schema and
$defs/profile_rule_key, rule_reason, rule_expiry_preset can never drift apart.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VALUES = "schemas/common/profile-rule-values.json"
RESOLVED = "schemas/common/resolved-rules.json"

# Every Android device class gets the rules of its Apple counterpart (phone like iPhone,
# tablet like iPad incl. wall panel, TV like Apple TV, wearos like watchos).
ANDROID_COUNTERPART = {"ios": "android", "ipados": "android_tablet", "tvos": "android_tv", "watchos": "wearos"}
# Rules that deliberately skip an Android counterpart: {rule key: {platform: reason}}. A rule that
# only makes sense on Apple hardware (e.g. a Siri- or Action-button-only feature) belongs here.
# quick_access maps to widgets, quick settings tiles and device controls, watch to a wearos watch,
# app_settings_biometrics to the fingerprint/face unlock. A rule the Android platform does not
# offer is listed here, so the admin UI shows it as "not applicable" on Android instead of
# "in effect". Add the platform back to the catalog when it offers the rule.
_NOT_OFFERED = "not offered on this Android platform"
ANDROID_EXCLUDED: dict[str, dict[str, str]] = {
    "notification_level": {p: _NOT_OFFERED for p in ("android", "android_tablet", "android_tv")},
    "notification_stack": {p: _NOT_OFFERED for p in ("android", "android_tablet", "android_tv")},
    "search_filter": {p: _NOT_OFFERED for p in ("android", "android_tablet")},
    "power_button": {p: _NOT_OFFERED for p in ("android", "android_tablet")},
    "card_style": {p: _NOT_OFFERED for p in ("android", "android_tablet", "android_tv")},
    "panel_off_mode": {"android_tablet": _NOT_OFFERED},
    "appearance": {"android_tv": "Android TV uses one fixed dark theme"},
    "columns": {"android_tablet": "the Android tablet layout has no area grid; only the phone grid follows the rule"},
    "kids_watch": {"android": "a child's watch is offered for iPhone only"},
}
# Rules of class normal a watch is still limited in (the app enforces them: a watch never shows more
# advanced controls than its phone).
WATCH_LIMIT_EXTRA = ("control_mode_max",)
# Boundaries that may carry lifted_by (None = any earlier boolean kids rule).
LIFTED_BY = {"child_protection": None, "hub_only": "remote_access"}
# Profile kinds whose devices are guest accesses with an expiry.
GUEST_KINDS = ("guest", "house_sitter", "babysitter")


def _load(repo: Path, rel: str):
    return json.loads((repo / rel).read_text(encoding="utf-8"))


def build_resolved(repo: Path = REPO) -> dict:
    values = _load(repo, VALUES)
    catalog = _load(repo, "data/profile-rules.json")
    labels = {r["key"]: r["label"]["en"] for r in catalog["rules"]}
    props = {}
    for key in values["properties"]:
        ref = {"$ref": f"profile-rule-values.json#/properties/{key}"}
        props[key] = {
            "type": "object",
            "description": f"{labels.get(key, key)}: effective value with its source (generated by tools/profile_rules.py).",
            "required": ["value", "source", "reason", "locked", "fixed"],
            "properties": {
                "value": ref,
                "source": {"$ref": "defs.json#/$defs/rule_source"},
                "reason": {"$ref": "defs.json#/$defs/rule_reason"},
                "locked": {"type": "boolean", "description": "true = the person at the device must not change the value (everything except user_choice)."},
                "fixed": {"type": "boolean", "description": "true = the admin cannot adjust the rule on this device (profile checkbox “Fixed”, or decided by a boundary). Display only."},
                "user_choice": {"type": "boolean", "description": "true = the person at the device decides; value is the starting value and replaces nothing the person chose locally. Missing = false."},
                "expires_at": {"anyOf": [{"$ref": "defs.json#/$defs/timestamp"}, {"type": "null"}],
                               "description": "Temporary device adjustment: end (UTC). The app switches to then at this time even offline; the hub sends client_config_updated."},
                "then": {"anyOf": [ref, {"type": "null"}], "description": "Value after expires_at (only with expires_at)."},
                "set_by": {"anyOf": [{"type": "string", "maxLength": 100}, {"type": "null"}],
                           "description": "Display name of who set the device adjustment (admin or family manager device); only with source device. Apps use it instead of {admin} in the reason sentence."},
                "enforcement": {"$ref": "defs.json#/$defs/rule_enforcement",
                                "description": "Who enforces it on this device: ha/hub = show “Enforced”, app = “Applies in <brand>”."},
            },
            "additionalProperties": True,
        }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "client_config.rules",
        "description": "Effective profile rules of the device, resolved by the hub (catalog default -> profile -> device adjustment, possibly temporary -> boundaries guest access and parental controls -> prerequisites). Only rules that apply to the device's platform (and kids rules only with parental controls) are present; a missing rule keeps the app's own behavior. Clients ignore unknown rules and unknown source/reason values. GENERATED by tools/profile_rules.py from profile-rule-values.json - do not edit.",
        "type": "object",
        "properties": props,
        "additionalProperties": True,
    }


def render(doc: dict) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def _value_validator(repo: Path):
    from jsonschema import Draft202012Validator  # noqa: PLC0415
    from referencing import Registry, Resource  # noqa: PLC0415
    from referencing.jsonschema import DRAFT202012  # noqa: PLC0415
    import urllib.parse  # noqa: PLC0415

    def retrieve(uri: str):
        path = Path(urllib.parse.unquote(urllib.parse.urlparse(uri).path))
        doc = json.loads(path.read_text())
        doc["$id"] = path.resolve().as_uri()
        return Resource.from_contents(doc, default_specification=DRAFT202012)

    registry = Registry(retrieve=retrieve)
    base = (repo / VALUES).resolve().as_uri()
    cache = {}

    def check(key: str, value) -> list[str]:
        if key not in cache:
            cache[key] = Draft202012Validator({"$ref": f"{base}#/properties/{key}"}, registry=registry,
                                              format_checker=Draft202012Validator.FORMAT_CHECKER)
        return [f"{'/'.join(map(str, e.path)) or '<value>'}: {e.message}" for e in cache[key].iter_errors(value)]

    return check


def _key_platforms() -> tuple:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import profiles_ref  # noqa: PLC0415

    return profiles_ref.KEY_PLATFORMS


def _control_path_checks(by_key: dict) -> list[str]:
    """control_path: hub, checked, direct (strict to loose); no boundary gives direct; hub_only only on
    rules after it (checked with the boundaries); the key platforms are platforms of the rule."""
    errs: list[str] = []
    where = "data/profile-rules.json rule control_path"
    r = by_key.get("control_path")
    if r is None:
        return [f"{where}: missing"]
    if r["order"] != ["hub", "checked", "direct"] or r["strictest"] != "hub":
        errs.append(f"{where}: order must be hub, checked, direct (strictest hub)")
    for b in r["boundaries"]:
        if b["boundary"] == "hub_only":
            errs.append(f"{where}: hub_only cannot cap control_path itself")
        elif b["cap"] == "direct":
            errs.append(f"{where}: boundary {b['boundary']} must cap below direct")
    key_platforms = _key_platforms()
    if not set(key_platforms) <= set(r["platforms"]):
        errs.append(f"{where}: applies to every key platform {list(key_platforms)}")
    return errs


def check(repo: Path = REPO) -> list[str]:
    errs: list[str] = []
    catalog = _load(repo, "data/profile-rules.json")
    suggestions = _load(repo, "data/profile-suggestions.json")
    values = _load(repo, VALUES)
    defs = _load(repo, "schemas/common/defs.json")["$defs"]
    vcheck = _value_validator(repo)

    keys = [r["key"] for r in catalog["rules"]]
    if len(set(keys)) != len(keys):
        errs.append("data/profile-rules.json: duplicate rule key")
    if keys != list(values["properties"]):
        errs.append(f"{VALUES}: properties differ from the catalog keys (same order required)")
    if keys != defs["profile_rule_key"]["enum"]:
        errs.append("defs.json profile_rule_key differs from the catalog keys (same order required)")
    codes = [r["code"] for r in catalog["reasons"]]
    if sorted(codes) != sorted(defs["rule_reason"]["enum"]) or len(set(codes)) != len(codes):
        errs.append("data/profile-rules.json reasons differ from defs.json rule_reason")
    if [e["id"] for e in catalog["expiry_presets"]] != defs["rule_expiry_preset"]["enum"]:
        errs.append("data/profile-rules.json expiry_presets differ from defs.json rule_expiry_preset")
    if sorted(b["id"] for b in catalog["boundaries"]) != sorted(defs["rule_boundary"]["enum"]):
        errs.append("data/profile-rules.json boundaries differ from defs.json rule_boundary")
    if sorted(e["id"] for e in catalog["enforcement"]) != sorted(defs["rule_enforcement"]["enum"]):
        errs.append("data/profile-rules.json enforcement texts differ from defs.json rule_enforcement")
    groups = [g["id"] for g in catalog["groups"]]
    if groups != defs["profile_rule_group"]["enum"]:
        errs.append("data/profile-rules.json groups differ from defs.json profile_rule_group")
    reason_source = {r["code"]: r["source"] for r in catalog["reasons"]}
    kinds = defs["profile_kind"]["enum"]
    if [k["id"] for k in catalog["profile_kinds"]] != kinds:
        errs.append("data/profile-rules.json profile_kinds differ from defs.json profile_kind (same order required)")
    for pk in catalog["profile_kinds"]:
        if pk["guest_access"] != (pk["id"] in GUEST_KINDS):
            errs.append(f"data/profile-rules.json profile_kinds {pk['id']}: guest_access only for {', '.join(GUEST_KINDS)}")

    for r in catalog["rules"]:
        k = r["key"]
        where = f"data/profile-rules.json rule {k}"
        for m in vcheck(k, r["default"]):
            errs.append(f"{where}: default: {m}")
        if r["group"] not in groups:
            errs.append(f"{where}: unknown group")
        if r["profile_kinds"] is not None and set(r["profile_kinds"]) - set(kinds):
            errs.append(f"{where}: unknown profile kind")
        if r["requires_child_protection"] != (r["group"] == "kids"):
            errs.append(f"{where}: kids rules (and only they) require parental controls")
        if not r["user_choice_allowed"] and r["default_user_choice"]:
            errs.append(f"{where}: default_user_choice without user_choice_allowed")
        if not r["fixed_checkbox"] and not r["default_fixed"]:
            errs.append(f"{where}: a rule without checkbox is always fixed (default_fixed true)")
        if r["user_choice_allowed"] and r["security"] != "normal":
            errs.append(f"{where}: user's choice only for normal rules")
        order = r["order"]
        if order is not None:
            for v in order:
                for m in vcheck(k, v):
                    errs.append(f"{where}: order value {v!r}: {m}")
        if r["security"] != "normal" and not r["requires_child_protection"] and r["strictest"] is None:
            errs.append(f"{where}: critical/sensitive rules need strictest (guest expiry)")
        if r["strictest"] is not None:
            for m in vcheck(k, r["strictest"]):
                errs.append(f"{where}: strictest: {m}")
            if order is not None and r["strictest"] != order[0]:
                errs.append(f"{where}: strictest must be the first value of order")
        seen = set()
        for b in r["boundaries"]:
            if b["boundary"] in seen:
                errs.append(f"{where}: boundary {b['boundary']} twice")
            seen.add(b["boundary"])
            if order is None:
                # Without order an active boundary always decides (value = cap).
                for m in vcheck(k, b["cap"]):
                    errs.append(f"{where}: cap: {m}")
                if r["strictest"] is not None and b["cap"] != r["strictest"]:
                    errs.append(f"{where}: a boundary of a rule without order caps to strictest")
            elif b["cap"] not in order:
                errs.append(f"{where}: cap {b['cap']!r} not in order")
            if reason_source.get(b["reason"]) != "boundary":
                errs.append(f"{where}: boundary reason {b['reason']} must have source boundary")
            if b["boundary"] == "hub_only" and keys.index("control_path") >= keys.index(k):
                # hub_only is active while control_path resolved to hub: it must be resolved first.
                errs.append(f"{where}: a hub_only boundary needs control_path before {k} in the catalog")
            lifted = b.get("lifted_by")
            if lifted is not None:
                # Parental controls are lifted only by an earlier boolean kids rule, hub_only only by
                # remote_access (it gives the device a read-only key); both are resolved first.
                lr = next((x for x in catalog["rules"] if x["key"] == lifted), None)
                if b["boundary"] not in LIFTED_BY:
                    errs.append(f"{where}: lifted_by only on the boundaries {', '.join(LIFTED_BY)}")
                elif b["boundary"] == "hub_only" and lifted != LIFTED_BY["hub_only"]:
                    errs.append(f"{where}: hub_only is lifted only by remote_access")
                if lr is None or lr["type"] != "boolean":
                    errs.append(f"{where}: lifted_by {lifted} must be a boolean rule")
                elif b["boundary"] == "child_protection" and not lr["requires_child_protection"]:
                    errs.append(f"{where}: lifted_by {lifted} must be a boolean kids rule")
                elif keys.index(lifted) > keys.index(k):
                    errs.append(f"{where}: lifted_by {lifted} must come before {k} in the catalog")
                elif not set(r["platforms"]) & set(lr["platforms"]):
                    errs.append(f"{where}: lifted_by {lifted} applies to none of its platforms")
        # A watch follows its phone: every rule is classified (never a silent "replace").
        wl = r.get("watch_limit")
        must = k in WATCH_LIMIT_EXTRA or k == "areas" or (
            r["security"] in ("critical", "sensitive") and r["group"] not in ("kids", "location"))
        if wl is None:
            errs.append(f"{where}: watch_limit missing (classify the rule)")
        elif must and wl == "none":
            errs.append(f"{where}: a No-escalation rule must be limited for watches (watch_limit)")
        elif not must and wl != "none":
            errs.append(f"{where}: watch_limit {wl} on a rule a watch is not limited in")
        elif wl == "ordered" and not order:
            errs.append(f"{where}: watch_limit ordered needs order")
        elif wl in ("areas", "schedule", "remote_levels", "kinds") and \
                {"areas": "areas", "schedule": "access_hours", "remote_levels": "remote_control",
                 "kinds": "setup_devices"}[wl] != k:
            errs.append(f"{where}: watch_limit {wl} is only defined for its own rule")
        p = r["prerequisite"]
        if p is not None:
            for field in ("when", "otherwise"):
                for m in vcheck(k, p[field]):
                    errs.append(f"{where}: prerequisite.{field}: {m}")
            if order is not None and order.index(p["otherwise"]) >= order.index(p["when"]):
                errs.append(f"{where}: prerequisite.otherwise must be stricter than when")
        if r["security"] != "normal" and r["loosening_warning"] is None and r["order"] is not None and not r["requires_child_protection"]:
            errs.append(f"{where}: loosening_warning missing for a security rule")
        for apple, android in ANDROID_COUNTERPART.items():
            if apple in r["platforms"] and android not in r["platforms"] and android not in ANDROID_EXCLUDED.get(k, {}):
                errs.append(f"{where}: applies to {apple} but not to {android} (or list it in ANDROID_EXCLUDED with a reason)")
            if android in r["platforms"] and apple not in r["platforms"]:
                errs.append(f"{where}: applies to {android} but not to {apple}")
    by_key = {r["key"]: r for r in catalog["rules"]}
    errs += _control_path_checks(by_key)
    for k, excluded in ANDROID_EXCLUDED.items():
        if k not in by_key:
            errs.append(f"tools/profile_rules.py ANDROID_EXCLUDED: unknown rule {k}")
            continue
        for android in excluded:
            if android in by_key[k]["platforms"]:
                errs.append(f"tools/profile_rules.py ANDROID_EXCLUDED: {k} applies to {android} again in the "
                            f"catalog; remove the exclusion")
            elif android not in ANDROID_COUNTERPART.values():
                errs.append(f"tools/profile_rules.py ANDROID_EXCLUDED: {k}: unknown platform {android}")
    for g in groups:
        if g not in {r["group"] for r in catalog["rules"]}:
            errs.append(f"data/profile-rules.json: group {g} has no rule")

    rules = {r["key"]: r for r in catalog["rules"]}
    always_fixed = {k for k, r in rules.items() if not r["fixed_checkbox"]}
    uc_allowed = {k for k, r in rules.items() if r["user_choice_allowed"]}
    ids = [s["id"] for s in suggestions["suggestions"]]
    if len(set(ids)) != len(ids):
        errs.append("data/profile-suggestions.json: duplicate id")
    slots: dict[str, str] = {}
    for s in suggestions["suggestions"]:
        where = f"data/profile-suggestions.json {s['id']}"
        if s["default_for"] and not s["starter"]:
            errs.append(f"{where}: default_for only on starter suggestions")
        for slot in s["default_for"]:
            if slot in slots:
                errs.append(f"{where}: default_for {slot} already on {slots[slot]}")
            slots[slot] = s["id"]
        for apple, android in ANDROID_COUNTERPART.items():
            if (apple in s["default_for"]) != (android in s["default_for"]):
                errs.append(f"{where}: default_for must hold {apple} and {android} together")
        if not always_fixed <= set(s["fixed"]):
            errs.append(f"{where}: fixed must contain {sorted(always_fixed)}")
        if not set(s["user_choice"]) <= uc_allowed:
            errs.append(f"{where}: user_choice not allowed for {sorted(set(s['user_choice']) - uc_allowed)}")
        if s["kind"] not in kinds:
            errs.append(f"{where}: unknown kind {s['kind']}")
        for key, value in s["rules"].items():
            pk = rules.get(key, {}).get("profile_kinds")
            if pk is not None and s["kind"] not in pk:
                errs.append(f"{where}: rule {key} does not apply to kind {s['kind']}")
        if s["kind"] in GUEST_KINDS and s["child_protection"]:
            errs.append(f"{where}: kind {s['kind']} is a guest access and never has parental controls")
        if s["intended_for"] == "guest" and s["child_protection"]:
            errs.append(f"{where}: guests never get parental controls in v1.0")
        patterns = s.get("area_patterns")
        if patterns and (s["rules"].get("areas") or {}).get("mode") != "selected":
            errs.append(f"{where}: area_patterns only with areas mode selected")
        path = s["rules"].get("control_path", rules["control_path"]["default"])
        if s["kind"] in GUEST_KINDS and (path != "hub" or "control_path" not in s["fixed"]):
            errs.append(f"{where}: guest kinds read and switch only through the hub (control_path hub, fixed)")
        if s["child_protection"] and path != "hub":
            errs.append(f"{where}: suggestions with parental controls start on the hub path (control_path hub)")
        if path == "hub" and (s["kind"] == "tv" or set(s["default_for"]) & set(_key_platforms())):
            errs.append(f"{where}: control_path hub on a platform that needs its own key (tools/profiles_ref.py "
                        f"KEY_PLATFORMS)")
        if s["starter"] is False and s["id"] in ("adult", "child", "guest", "wall_panel", "apple_tv"):
            errs.append(f"{where}: must be a starter")
    missing = set(defs["default_profile_slot"]["enum"]) - set(slots)
    if missing:
        errs.append(f"data/profile-suggestions.json: no starter is default for {sorted(missing)}")
    starters = sorted(s["id"] for s in suggestions["suggestions"] if s["starter"])
    if starters != sorted(["adult", "child", "guest", "wall_panel", "apple_tv"]):
        errs.append(f"data/profile-suggestions.json: starters must be the five starter profiles, found {starters}")

    current = (repo / RESOLVED).read_text(encoding="utf-8") if (repo / RESOLVED).exists() else None
    if current != render(build_resolved(repo)):
        errs.append(f"{RESOLVED} is stale: run python tools/profile_rules.py")
    return errs


def main(argv: list[str]) -> int:
    if "--check" in argv:
        errs = check()
        for e in errs:
            print(e)
        print("profile rules: ok" if not errs else f"profile rules: {len(errs)} error(s)")
        return 1 if errs else 0
    (REPO / RESOLVED).write_text(render(build_resolved()), encoding="utf-8")
    print(f"wrote {RESOLVED}")
    errs = check()
    for e in errs:
        print(e)
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
